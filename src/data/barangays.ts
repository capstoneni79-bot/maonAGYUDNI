/**
 * Helper to get exact coordinates for any given barangay name
 */
export function getBarangayCoordinates(barangayName: string): { latitude: number; longitude: number } {
  const normalized = (barangayName || '').toLowerCase().trim();
  const match = HINUNANGAN_BARANGAYS.find(
    b => b.name.toLowerCase() === normalized || b.code.toLowerCase() === normalized
  );
  if (match) {
    return { latitude: match.latitude, longitude: match.longitude };
  }
  // Default centroid of Hinunangan (Poblacion)
  return { latitude: 10.397795817414737, longitude: 125.19936456914245 };
}

/**
 * Helper to find the closest official barangay to a given coordinate
 */
export function findClosestBarangay(lat: number, lng: number): HinunanganBarangayGeo {
  let closest = HINUNANGAN_BARANGAYS[0];
  let minDistance = Infinity;

  for (const b of HINUNANGAN_BARANGAYS) {
    const dist = Math.hypot(b.latitude - lat, b.longitude - lng);
    if (dist < minDistance) {
      minDistance = dist;
      closest = b;
    }
  }

  return closest;
}
